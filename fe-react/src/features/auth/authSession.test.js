import { describe, expect, it, vi } from 'vitest'
import { createAuthSession } from './authSession.js'
import { createSessionStorage } from './sessionStorage.js'
import { deferred, jsonResponse, testSession, userFixture } from '../../test/authFixtures.js'
import { queryKeys } from '../../app/queryKeys.js'
import { retryRead } from '../../app/queryClient.js'

describe('authentication/session isolation (mocked API)', () => {
  it('ignores corrupt stored user and forged role until /me is verified', async () => {
    localStorage.clear()
    localStorage.setItem('token', 'fixture')
    localStorage.setItem('user', '{broken ADMIN')
    const pending = deferred()
    const session = createAuthSession({ fetchImpl: () => pending.promise })
    const start = session.start()
    expect(session.getSnapshot()).toMatchObject({ status: 'verifying', user: null })
    pending.resolve(jsonResponse(userFixture('STUDENT')))
    await start
    expect(session.getSnapshot().user.role).toBe('STUDENT')
    expect(JSON.parse(localStorage.getItem('user')).role).toBe('STUDENT')
    session.stop(); localStorage.clear()
  })
  it('fails safely with inaccessible storage and can log in for this tab', async () => {
    const storage = createSessionStorage(() => { throw new Error('SecurityError') })
    const session = createAuthSession({ storage, fetchImpl: async (path) => jsonResponse(path.endsWith('/login') ? { token: 'new' } : userFixture()) })
    await session.start()
    expect(session.getSnapshot().status).toBe('anonymous')
    await session.login({ username: 'test', password: 'fixture' })
    expect(session.getSnapshot().status).toBe('authenticated')
    expect(session.getSnapshot().notice).toContain('Không lưu được')
    session.logout()
    expect(session.getSnapshot().status).toBe('anonymous')
    session.stop()
  })
  it('invalid token 401 ends restore; network failure keeps token for manual retry', async () => {
    const fetchImpl = vi.fn().mockRejectedValueOnce(new TypeError('offline')).mockResolvedValueOnce(jsonResponse(userFixture()))
    const { session, storage } = testSession({ fetchImpl })
    await session.start()
    expect(session.getSnapshot()).toMatchObject({ status: 'verifying', user: null, error: { status: 0 } })
    expect(storage.clear).not.toHaveBeenCalled()
    await session.retryVerify()
    expect(session.getSnapshot().status).toBe('authenticated')
    fetchImpl.mockResolvedValueOnce(jsonResponse({}, 401))
    await expect(session.getSnapshot().api('/api/test')).rejects.toMatchObject({ status: 401 })
    expect(session.getSnapshot().status).toBe('anonymous')
    expect(storage.clear).toHaveBeenCalledTimes(1)
    session.stop()
  })
  it('403 preserves authenticated session; expired startup token removes legacy keys', async () => {
    const { session, fetchMock } = testSession()
    await session.start()
    fetchMock.mockResolvedValueOnce(jsonResponse({ message: 'No permission' }, 403))
    await expect(session.getSnapshot().api('/api/admin/users')).rejects.toMatchObject({ status: 403 })
    expect(session.getSnapshot().status).toBe('authenticated')
    session.stop()
    const expired = testSession({ fetchImpl: async () => jsonResponse({}, 401) })
    await expired.session.start()
    expect(expired.session.getSnapshot().status).toBe('anonymous')
    expect(expired.storage.clear).toHaveBeenCalled()
    expired.session.stop()
  })
  it.each([200, 401])('old request HTTP %s cannot affect a newly logged-in account', async (status) => {
    const pending = deferred()
    const { session, fetchMock } = testSession()
    await session.start()
    const old = session.getSnapshot()
    fetchMock.mockImplementationOnce(() => pending.promise)
    const request = old.api('/api/old').catch((error) => error)
    session.logout()
    fetchMock.mockResolvedValueOnce(jsonResponse({ token: 'student-token' })).mockResolvedValueOnce(jsonResponse(userFixture('STUDENT')))
    await session.login({ username: 'student', password: 'fixture' })
    pending.resolve(jsonResponse(userFixture('ADMIN'), status))
    expect(await request).toMatchObject({ name: 'AbortError' })
    expect(session.getSnapshot().user.role).toBe('STUDENT')
    session.stop()
  })
  it('old restore cannot replace new login, and StrictMode-style restart works', async () => {
    const pending = deferred()
    const fetchImpl = vi.fn().mockImplementationOnce(() => pending.promise).mockResolvedValueOnce(jsonResponse({ token: 'new' })).mockResolvedValueOnce(jsonResponse(userFixture('STUDENT')))
    const { session } = testSession({ fetchImpl })
    const start = session.start()
    session.stop()
    await session.login({ username: 'new', password: 'fixture' })
    pending.resolve(jsonResponse(userFixture('ADMIN')))
    await start
    expect(session.getSnapshot().user.role).toBe('STUDENT')
    session.stop()
    fetchImpl.mockResolvedValueOnce(jsonResponse(userFixture('STUDENT')))
    await session.start()
    expect(session.getSnapshot().status).toBe('authenticated')
    session.stop()
  })
  it('logout cancels query signal and clears queries/mutations; late completion never enters the new cache', async () => {
    const { session } = testSession()
    await session.start()
    const old = session.getSnapshot(), pending = deferred()
    const key = queryKeys.list(old.sessionId, 'students', { page: 2, q: 'test' })
    old.queryClient.setQueryData(['private'], 'secret')
    old.queryClient.getMutationCache().build(old.queryClient, { mutationKey: ['private'] })
    let querySignal
    const result = old.queryClient.fetchQuery({ queryKey: key, queryFn: ({ signal }) => { querySignal = signal; return pending.promise } }).catch(() => null)
    session.logout()
    expect(querySignal.aborted).toBe(true)
    expect(old.queryClient.getQueryCache().getAll()).toHaveLength(0)
    expect(old.queryClient.getMutationCache().getAll()).toHaveLength(0)
    expect(session.getSnapshot().queryClient).not.toBe(old.queryClient)
    pending.resolve('old secret')
    await result
    expect(session.getSnapshot().queryClient.getQueryCache().getAll()).toHaveLength(0)
    session.stop()
  })
  it('storage token change verifies new account; storage logout clears session', async () => {
    const { session, storage, fetchMock } = testSession()
    await session.start()
    storage.save('new', null)
    fetchMock.mockResolvedValueOnce(jsonResponse(userFixture('STUDENT')))
    session.syncStorage()
    expect(session.getSnapshot().status).toBe('verifying')
    await vi.waitFor(() => expect(session.getSnapshot().user?.role).toBe('STUDENT'))
    storage.clear()
    session.syncStorage()
    expect(session.getSnapshot().status).toBe('anonymous')
    session.stop()
  })
  it('retry policy excludes auth, permission, client errors, aborts and mutations; keys isolate all params', () => {
    for (const status of [400, 401, 403, 404, 429]) expect(retryRead(0, { status })).toBe(false)
    expect(retryRead(0, { name: 'AbortError' })).toBe(false)
    expect(retryRead(0, { status: 500 })).toBe(true)
    expect(retryRead(2, { status: 500 })).toBe(false)
    const { session } = testSession()
    expect(session.getSnapshot().queryClient.getDefaultOptions().mutations.retry).toBe(false)
    expect(queryKeys.detail(1, 'transcript', 42, { semester: 2 })).toEqual(['session', 1, 'transcript', 'detail', '42', { semester: 2 }])
    expect(queryKeys.list(1, 'students', { page: 1 })).not.toEqual(queryKeys.list(1, 'students', { page: 2 }))
    session.stop()
  })
})
