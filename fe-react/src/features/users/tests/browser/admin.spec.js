import { test, expect } from '@playwright/test'
import { mockAdministration } from './adminBrowserFixture.js'
import { adminStudent } from '../adminFixtures.js'

for (const width of [360, 1280]) {
  test(`student create/edit/delete, field errors, focus and responsive form at ${width}px (fixture)`, async ({ page }, testInfo) => {
    const state = await mockAdministration(page)
    const errors = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.setViewportSize({ width, height: 850 })
    await page.goto('/#/students')
    await page.getByRole('button', { name: '＋ Thêm sinh viên' }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('button', { name: 'Lưu sinh viên' }).click()
    await expect(dialog.getByLabel('Mã sinh viên')).toBeFocused()
    await expect(dialog.getByLabel('Họ tên', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    expect(state.writes).toHaveLength(0)
    await dialog.getByLabel('Mã sinh viên').fill('SVNEW43')
    await dialog.getByLabel('Họ tên', { exact: true }).fill('Sinh viên mới')
    await dialog.getByLabel('Ngày sinh').fill('2004-02-29')
    await dialog.getByLabel('Lớp', { exact: true }).selectOption('1')
    await dialog.getByLabel('Email', { exact: true }).fill('new@example.test')
    expect(await dialog.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath(`student-form-${width}.png`), animations: 'disabled', fullPage: true })
    state.errors['POST /api/students'] = { status: 409, message: 'Mã sinh viên hoặc tên đăng nhập đã tồn tại' }
    await dialog.getByRole('button', { name: 'Lưu sinh viên' }).click()
    await expect(dialog.getByRole('alert')).toContainText('đã tồn tại')
    await expect(dialog.getByLabel('Họ tên', { exact: true })).toHaveValue('Sinh viên mới')
    delete state.errors['POST /api/students']
    await dialog.getByRole('button', { name: 'Lưu sinh viên' }).click()
    await expect(dialog).not.toBeVisible()
    await expect(page.getByRole('table').getByText('SVNEW43', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Sửa SVNEW43', exact: true }).click()
    await expect(dialog.getByLabel('Mã sinh viên')).toHaveAttribute('readonly', '')
    await dialog.getByLabel('Họ tên', { exact: true }).fill('Tên sinh viên đã sửa')
    await dialog.getByRole('button', { name: 'Lưu sinh viên' }).click()
    await expect(dialog).not.toBeVisible()
    await expect(page.getByRole('table').getByText('Tên sinh viên đã sửa')).toBeVisible()
    const trigger = page.getByRole('button', { name: 'Xóa SVNEW43', exact: true })
    await trigger.click()
    await expect(dialog).toHaveAccessibleDescription(/SVNEW43 — Tên sinh viên đã sửa/)
    await expect(dialog.getByRole('button', { name: 'Hủy', exact: true })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await trigger.click()
    await dialog.getByRole('button', { name: 'Xóa sinh viên', exact: true }).click()
    await expect(dialog).not.toBeVisible()
    await expect(page.getByRole('table').getByText('SVNEW43', { exact: true })).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    expect(state.writes.map(({ method, path }) => `${method} ${path}`)).toEqual(['POST /api/students', 'POST /api/students', 'PUT /api/students/43', 'DELETE /api/students/43'])
    expect(state.writes[2].body).not.toHaveProperty('student_code')
    expect(state.writes[1].body).not.toHaveProperty('password')
    expect(state.unexpected).toEqual([])
    expect(errors).toEqual([])
  })
}

test('delete the final row of the last filtered page without losing filters (fixture)', async ({ page }) => {
  const state = await mockAdministration(page)
  state.students = Array.from({ length: 13 }, (_, index) => ({ ...adminStudent, id: 100 + index, student_code: `SV${100 + index}` }))
  await page.goto('/#/students?q=SV&class_id=1&status=ACTIVE&page=2')
  await page.getByRole('button', { name: 'Xóa SV112', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Xóa sinh viên', exact: true }).click()
  await expect(page).toHaveURL(/#\/students\?q=SV&class_id=1&status=ACTIVE$/)
  await expect(page.getByRole('table').locator('tbody tr')).toHaveCount(12)
  await expect(page.getByLabel('Mã / tên')).toHaveValue('SV')
  await page.reload()
  await expect(page.getByLabel('Lớp', { exact: true })).toHaveValue('1')
  expect(state.writes).toEqual([{ method: 'DELETE', path: '/api/students/112', body: undefined }])
})

test('account confirmation keyboard/pending, status boolean and reset errors (fixture)', async ({ page }, testInfo) => {
  const state = await mockAdministration(page)
  await page.setViewportSize({ width: 360, height: 850 })
  await page.goto('/#/users')
  await expect(page.getByRole('button', { name: 'Khóa admin', exact: true })).toBeDisabled()
  const trigger = page.getByRole('button', { name: 'Khóa svtest42', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toHaveAccessibleDescription(/svtest42 — Sinh viên quản trị/)
  await expect(dialog.getByRole('button', { name: 'Hủy', exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Đóng hộp thoại' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Khóa tài khoản', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  expect(state.writes).toHaveLength(0)
  await trigger.click()
  let release
  state.gates['PATCH /api/admin/users/9/active'] = new Promise((resolve) => { release = resolve })
  await dialog.getByRole('button', { name: 'Khóa tài khoản', exact: true }).dblclick()
  await expect(dialog.getByRole('button', { name: 'Đang xử lý...' })).toBeDisabled()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  expect(state.writes).toEqual([{ path: '/api/admin/users/9/active', method: 'PATCH', body: { is_active: false } }])
  release()
  await expect(dialog).not.toBeVisible()
  await page.getByRole('button', { name: 'Mở khóa svtest42', exact: true }).click()
  await dialog.getByRole('button', { name: 'Mở khóa tài khoản', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  expect(state.writes.at(-1).body).toEqual({ is_active: true })
  state.errors['POST /api/admin/users/9/reset-password'] = { status: 403, message: 'Bạn không đủ quyền đặt lại mật khẩu' }
  await page.getByRole('button', { name: 'Đặt lại mật khẩu svtest42', exact: true }).click()
  await dialog.getByRole('button', { name: 'Đặt lại mật khẩu', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('không đủ quyền')
  await page.screenshot({ path: testInfo.outputPath('reset-error-mobile.png'), animations: 'disabled', fullPage: true })
  delete state.errors['POST /api/admin/users/9/reset-password']
  await dialog.getByRole('button', { name: 'Đặt lại mật khẩu', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'svtest42: Đã đặt lại mật khẩu' })).toContainText('student123')
  expect(state.writes.at(-1)).toEqual({ path: '/api/admin/users/9/reset-password', method: 'POST', body: undefined })
  expect(state.unexpected).toEqual([])
})

